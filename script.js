// ───────── LANGUAGE SWITCHER ─────────
let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  // Update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else if (el.tagName === 'OPTION') {
        el.textContent = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  // Update active language button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Store preference
  try { localStorage.setItem('thh-lang', lang); } catch(e) {}
}

// ───────── SCROLL EFFECTS ─────────
function handleScroll() {
  const header = document.querySelector('.header');
  if (window.scrollY > 50) {
    header.classList.add('scrolled');
  } else {
    header.classList.remove('scrolled');
  }

  // Fade in animations
  document.querySelectorAll('.fade-in').forEach(el => {
    const rect = el.getBoundingClientRect();
    if (rect.top < window.innerHeight - 100) {
      el.classList.add('visible');
    }
  });
}

// ───────── MOBILE MENU ─────────
function toggleMobile() {
  const nav = document.querySelector('.nav');
  nav.classList.toggle('active');
}

// ───────── SMOOTH SCROLL ─────────
function smoothScroll(target) {
  const el = document.querySelector(target);
  if (el) {
    el.scrollIntoView({ behavior: 'smooth', block: 'start' });
    // Close mobile menu
    document.querySelector('.nav').classList.remove('active');
  }
}

// ───────── FORM HANDLING ─────────
function handleFormSubmit(e) {
  e.preventDefault();
  const btn = e.target.querySelector('button[type="submit"]');
  const originalText = btn.textContent;
  btn.textContent = '✓';
  btn.style.background = '#10b981';
  setTimeout(() => {
    btn.textContent = originalText;
    btn.style.background = '';
    e.target.reset();
  }, 2000);
}

// ───────── INIT ─────────
document.addEventListener('DOMContentLoaded', () => {
  // Set initial language
  let savedLang;
  try { savedLang = localStorage.getItem('thh-lang'); } catch(e) {}
  setLanguage(savedLang || 'en');

  // Scroll handler
  window.addEventListener('scroll', handleScroll);
  handleScroll();

  // Form submit
  const form = document.querySelector('.contact-form');
  if (form) form.addEventListener('submit', handleFormSubmit);

  // Language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
  });

  // Mobile toggle
  const mobileBtn = document.querySelector('.mobile-toggle');
  if (mobileBtn) mobileBtn.addEventListener('click', toggleMobile);

  // Nav links smooth scroll
  document.querySelectorAll('.nav a, a[href^="#"]').forEach(link => {
    link.addEventListener('click', (e) => {
      const href = link.getAttribute('href');
      if (href && href.startsWith('#')) {
        e.preventDefault();
        smoothScroll(href);
      }
    });
  });
});
